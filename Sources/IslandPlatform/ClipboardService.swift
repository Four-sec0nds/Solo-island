import AppKit
import CryptoKit
import IslandCore
import UniformTypeIdentifiers

/// Reads all clipboard representations before marking a change as consumed.
@MainActor
public final class ClipboardService {
    public let assets: URL
    private var lastChange = -1
    private var retries = 0
    public init(folder: URL) { assets = folder.appendingPathComponent("Clipboard", isDirectory: true) }

    public func capture(_ pasteboard: NSPasteboard = .general, force: Bool = false) throws -> [ShelfEntry] {
        let change = pasteboard.changeCount
        guard force || change != lastChange else { return [] }
        let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        if privateTypes.contains(where: { pasteboard.types?.contains(.init($0)) == true }) {
            lastChange = change; return []
        }
        let entries: [ShelfEntry]
        do { entries = try read(pasteboard) }
        catch {
            retries += 1
            if retries < 8 { return [] }
            lastChange = change; retries = 0; throw error
        }
        // Promised files/screenshots can populate after the change counter increments.
        if entries.isEmpty, retries < 8 { retries += 1; return [] }
        lastChange = change; retries = 0
        return entries
    }
    private func read(_ pasteboard: NSPasteboard) throws -> [ShelfEntry] {
        let urls = fileURLs(pasteboard)
        if !urls.isEmpty { return try urls.map(importFile) }
        if let image = NSImage(pasteboard: pasteboard) { return [try importImage(image)] }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return [ShelfEntry(kind: .text, text: text)]
        }
        return []
    }
    private func fileURLs(_ pasteboard: NSPasteboard) -> [URL] {
        var urls: [URL] = []
        if let objects = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) {
            urls += objects.compactMap { ($0 as? NSURL).map { $0 as URL } }
        }
        for item in pasteboard.pasteboardItems ?? [] {
            if let string = item.string(forType: .fileURL), let url = URL(string: string), url.isFileURL { urls.append(url) }
        }
        if let paths = pasteboard.propertyList(forType: .init("NSFilenamesPboardType")) as? [String] {
            urls += paths.map { URL(fileURLWithPath: $0) }
        }
        var seen = Set<String>()
        return urls.filter { $0.isFileURL && seen.insert($0.standardizedFileURL.path).inserted }
    }
    public func importFile(_ url: URL) throws -> ShelfEntry {
        guard url.isFileURL, FileManager.default.fileExists(atPath: url.path) else {
            throw CocoaError(.fileNoSuchFile, userInfo: [NSFilePathErrorKey: url.path])
        }
        // Preserve screenshot/image bytes even when the source is a disappearing preview or temp file.
        let type = UTType(filenameExtension: url.pathExtension)
        if type?.conforms(to: .image) == true, let image = NSImage(contentsOf: url) {
            return try importImage(image)
        }
        return ShelfEntry(path: url.standardizedFileURL.path)
    }
    public func importImage(_ image: NSImage) throws -> ShelfEntry {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff),
              let png = bitmap.representation(using: .png, properties: [:]) else {
            throw CocoaError(.fileReadCorruptFile)
        }
        let digest = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        try FileManager.default.createDirectory(at: assets, withIntermediateDirectories: true)
        let url = assets.appendingPathComponent(digest + ".png")
        if !FileManager.default.fileExists(atPath: url.path) { try png.write(to: url, options: .atomic) }
        return ShelfEntry(path: url.path, kind: .image, isPinned: true)
    }
    public func removeOwnedImage(_ entry: ShelfEntry) {
        guard entry.kind == .image,
              entry.url.deletingLastPathComponent().standardizedFileURL == assets.standardizedFileURL,
              entry.url.lastPathComponent.range(of: "^[a-f0-9]{64}\\.png$", options: .regularExpression) != nil else { return }
        try? FileManager.default.removeItem(at: entry.url)
    }
}
